CREATE TABLE alarm_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(128) NOT NULL UNIQUE,
    element_id VARCHAR(128) NOT NULL,
    alarm_code VARCHAR(64) NOT NULL,
    severity VARCHAR(16) NOT NULL CHECK (severity IN ('INFO','WARNING','MAJOR','CRITICAL')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('RAISED','CLEARED')),
    event_timestamp BIGINT NOT NULL CHECK (event_timestamp >= 0),
    description VARCHAR(2048)
);
CREATE INDEX history_element_id_idx ON alarm_history(element_id, id DESC);
CREATE TABLE active_alarm (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    element_id VARCHAR(128) NOT NULL,
    alarm_code VARCHAR(64) NOT NULL,
    history_id BIGINT NOT NULL UNIQUE REFERENCES alarm_history(id),
    CONSTRAINT active_alarm_key UNIQUE(element_id, alarm_code)
);
